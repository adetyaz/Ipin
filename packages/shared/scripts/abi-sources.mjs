// Pure builder shared by gen-abi.mjs and test/abi.test.ts.
// vaultAbi = IPots ∪ IPolicyEngine: Wave 1 deploys one Vault implementing both
// (docs/api.md section 1); the interfaces are the source of truth.

const key = (item) =>
  item.type === "function" || item.type === "event" || item.type === "error"
    ? `${item.type}:${item.name}(${(item.inputs ?? []).map((i) => i.type).join(",")})`
    : item.type

export function buildAbis(read) {
  const seen = new Set()
  const vault = []
  for (const item of [...read("IPots"), ...read("IPolicyEngine")]) {
    const k = key(item)
    if (seen.has(k)) continue
    seen.add(k)
    vault.push(item)
  }
  const erc20 = read("IERC20")
  return [
    "// GENERATED by scripts/gen-abi.mjs from contracts/abi/*.json. Do not edit.",
    `export const vaultAbi = ${JSON.stringify(vault, null, 2)} as const`,
    "",
    `export const erc20Abi = ${JSON.stringify(erc20, null, 2)} as const`,
    "",
  ].join("\n")
}
